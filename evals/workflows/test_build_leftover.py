"""Build parent Leftover evidence fixture and grader tests. These never execute an agent.

Known good outcomes are produced by the installed skill's real tickets.sh against the offline tracker,
so the tests also prove the double answers every call the build progress check makes.
"""
import importlib.util
import json
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch

spec = importlib.util.spec_from_file_location('build_workflow_fixture', Path(__file__).with_name('run.py'))
run = importlib.util.module_from_spec(spec)
spec.loader.exec_module(run)

URL = 'https://github.com/fixture/mana'
PARENT_LINK = 'Build parent: [Build: Agent first screen](' + URL + '/issues/40)'
SOURCE_LINK = 'Planning source: [Map: Agent first screen](' + URL + '/issues/30)'
BRIEF = ('> *This was generated by AI during triage.*\n\n## Agent Brief\n\n**Category:** enhancement\n'
         '**Summary:** Record three passing agent first-screen runs on one merged revision.\n\n'
         '**Current behavior:**\nPR #52 merged the run harness and its closing keyword closed this ticket before any run.\n\n'
         '**Acceptance criteria:**\n- [ ] Three passing run logs on one merged revision, linked from the build parent\n')
CLOSEOUT = ('Check progress and close out the build effort at ' + URL + '/issues/40, '
            'reopening or filing tickets for its unmet evidence.')
READ_ONLY_REPORT = ('[Build: Agent first screen](' + URL + '/issues/40): every member is closed and no PR awaits review, '
                    'but no recorded agent run has passed, so Destination is unmet.\n'
                    'Actions not taken (read-only):\n'
                    '1. Post an `## Agent Brief` comment on #42 naming the three passing runs it owes.\n'
                    '2. Reopen #42, which clears its assignee.\n'
                    '3. Add the ready-for-agent label to #42.\n'
                    'Next step: ' + CLOSEOUT)
FILING_REPORT = ('[Build: Agent first screen](' + URL + '/issues/40): Destination is unmet.\n'
                 'Actions not taken (read-only):\n'
                 '1. File a new member ticket labelled enhancement and ready-for-agent, with Build parent and '
                 'Planning source lines and an `## Agent Brief` for the gate run.\n'
                 '2. Attach it under the build parent and add it to Build order.\n'
                 'Next step: ' + CLOSEOUT)


def event(command, output='', code=0):
    return {'type': 'item.completed', 'item': {'type': 'command_execution', 'command': command,
                                               'aggregated_output': output, 'exit_code': code}}


def implement(n):
    return 'Next step: Implement ' + URL + '/issues/' + n + ', following its brief.'


class BuildLeftover(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='mana build leftover ')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.cases = {c['id']: c for c in run.load_cases()}

    def fixture(self, name):
        self.case = self.cases[name]
        out = Path(tempfile.mkdtemp(dir=self.root))
        self.work, self.baseline = run.prepare(self.case, out)
        self.env = run.clean_env(self.work / 'home')
        self.env['PATH'] = str(self.work / 'bin') + ':/usr/bin:/bin'
        self.env['TMPDIR'] = str(self.work / 'artifacts')
        self.tickets = self.work / 'installed' / self.case['skill'] / 'scripts/tickets.sh'

    def t(self, *args, stdin=None, code=0):
        result = subprocess.run(['bash', str(self.tickets), '--repo', 'fixture/mana', *args], cwd=self.work,
                                env=self.env, input=stdin, text=True, capture_output=True)
        if code is not None:
            self.assertEqual(result.returncode, code, result.stderr)
        return result

    def gh(self, *args):
        return subprocess.run(['gh', *args], cwd=self.work, env=self.env, text=True, capture_output=True)

    def tracker(self):
        return json.loads((self.work / 'artifacts/tracker.json').read_text())

    def grade(self, report, commands=()):
        events = [event('bash ' + str(self.tickets) + ' --repo fixture/mana children 40')]
        events += [event(c) for c in commands]
        return run.grade(self.case, self.work, self.baseline, {'report': report, 'checks': []}, events)

    def reconcile(self):
        self.t('view', '40')
        rows = self.t('children', '40').stdout.splitlines()
        self.assertEqual([r.split('\t')[:2] for r in rows], [['41', 'CLOSED'], ['42', 'CLOSED']])
        self.t('blocked', '42', code=1)

    def edit_parent(self, change):
        snapshot = self.work / 'artifacts/parent-snapshot.md'
        snapshot.write_text(self.t('body', '40').stdout)
        self.t('update-body', '40', '--expected-body', str(snapshot), stdin=change(snapshot.read_text()))

    def reopen_owner(self):
        self.t('comment', '42', stdin=BRIEF)
        self.assertEqual(self.t('reopen', '42').stdout, 'reopened\t42\n')
        self.t('label', '42', '--add', 'ready-for-agent')
        self.edit_parent(lambda body: body.split('## Next step')[0]
                         + '## Next step\n\nImplement ' + URL + '/issues/42, following its brief.\n')

    def file_member(self, labels=('enhancement', 'ready-for-agent'), lines=(PARENT_LINK, SOURCE_LINK),
                    attach=True, order=True, brief=BRIEF, assignee=None):
        args = [x for label in labels for x in ('--label', label)]
        row = self.t('create', 'Agent first-screen gate run', *args, stdin='\n'.join(lines) + '\n\n' + brief).stdout
        n, url = row.strip().split('\t')
        if assignee:
            self.gh('issue', 'edit', n, '--add-assignee', assignee)
        if attach:
            self.t('attach', n, '40')
        if order:
            entry = ('3. Agent first-screen gate run. Ticket: [Agent first-screen gate run](' + url + '). After: 2.\n'
                     '   Outcome: three recorded agent runs on one merged revision pass the first-screen check.\n\n')
            self.edit_parent(lambda body: body.replace('## Next step', entry + '## Next step'))
        return n

    def test_offline_tracker_answers_reads_and_fails_closed(self):
        self.fixture('scry-build-leftover')
        self.assertIn('Work kind: build', self.t('view', '40').stdout)
        self.assertEqual(self.t('next', 'ready-for-agent').stdout.split('\t')[0], '99')
        found = self.t('find', URL + '/issues/30').stdout.splitlines()
        self.assertEqual([r.split('\t')[0] for r in found], ['40', '41', '42'])
        view = subprocess.run(['bash', str(self.work / 'installed/scry/scripts/map.sh'), 'view', '40'], cwd=self.work,
                              env=self.env, text=True, capture_output=True)
        self.assertEqual(view.returncode, 0, view.stderr)
        self.assertTrue(view.stdout.startswith('number\t40\n'))
        self.assertEqual(self.gh('pr', 'list', '--repo', 'fixture/mana', '--json', 'number').stdout.strip(), '[]')
        merged = json.loads(self.gh('pr', 'list', '--state', 'merged', '--json', 'number,closingIssuesReferences').stdout)
        self.assertEqual([p['number'] for p in merged], [51, 52])
        refs = json.loads(self.gh('issue', 'view', '42', '--json', 'closedByPullRequestsReferences').stdout)
        self.assertEqual(refs['closedByPullRequestsReferences'][0]['number'], 52)
        for args in (('gist', 'list'), ('issue', 'view', '40', '--json', 'body', '--jq', '.body | test("x")'),
                     ('issue', 'view', '40', '--repo', 'other/repo'), ('api', 'repos/fixture/mana/issues/40/timeline'),
                     ('issue', 'list', '--search', 'runs'), ('label', 'list', '--search', 'ready'),
                     ('pr', 'list', '--head', 'agent-run-harness'), ('pr', 'list', '--search', 'author:builder')):
            with self.subTest(args=args):
                result = self.gh(*args)
                self.assertEqual(result.returncode, 97, result.stderr)
                self.assertNotIn('Traceback', result.stderr)
        self.assertEqual(self.tracker(), self.baseline['tracker'])

    def test_reopened_owner_with_brief_passes(self):
        self.fixture('scry-build-leftover')
        self.reconcile()
        self.reopen_owner()
        owner = self.tracker()['issues']['42']
        self.assertEqual((owner['state'], owner['assignees']), ('OPEN', []))
        self.assertIn('ready-for-agent', owner['labels'])
        self.t('blocked', '42', code=1)
        self.assertEqual(self.grade('[Build: Agent first screen](' + URL + '/issues/40): leftover evidence.\n'
                                    + implement('42')), [])

    def test_reopen_defects_fail(self):
        def no_brief():
            self.t('reopen', '42')
            self.t('label', '42', '--add', 'ready-for-agent')

        def reopen_first():
            self.t('reopen', '42')
            self.t('comment', '42', stdin=BRIEF)
            self.t('label', '42', '--add', 'ready-for-agent')

        def assignee_kept():
            self.t('comment', '42', stdin=BRIEF)
            self.gh('issue', 'reopen', '42')
            self.t('label', '42', '--add', 'ready-for-agent')

        def no_label():
            self.t('comment', '42', stdin=BRIEF)
            self.t('reopen', '42')

        def parent_closed():
            self.reopen_owner()
            self.t('close', '40')

        def sibling_reopened():
            self.reopen_owner()
            self.t('reopen', '41')

        def claimed():
            self.reopen_owner()
            self.t('next', 'ready-for-agent', '--claim')

        def order_lost():
            self.reopen_owner()
            self.edit_parent(lambda body: body.split('## Build order')[0] + '## Next step\n\nRecheck.\n')

        def destination_lost():
            self.reopen_owner()
            self.edit_parent(lambda body: body.replace('three recorded agent runs', 'one recorded agent run'))

        def completion_heading():
            self.reopen_owner()
            self.t('comment', '40', stdin='## Completion\n\nBoth tickets merged.\n')

        def completion_bold():
            self.reopen_owner()
            self.t('comment', '40', stdin='**Completion**: both tickets merged.\n')

        cases = [(no_brief, implement('42'), {'reopened ticket has no new agent brief', 'brief not posted before reopening'}),
                 (reopen_first, implement('42'), {'brief not posted before reopening'}),
                 (assignee_kept, implement('42'), {'reopened ticket kept its assignee'}),
                 (no_label, implement('42'), {'reopened ticket lacks the ready label'}),
                 (parent_closed, implement('42'), {'build parent closed with unmet evidence'}),
                 (sibling_reopened, implement('42'), {'ticket state or labels changed: 41', 'ticket claimed or released: 41'}),
                 (claimed, implement('42'), {'ticket claimed or released: 99'}),
                 (order_lost, implement('42'), {'existing Build order entries lost'}),
                 (destination_lost, implement('42'), {'build parent body lost its marker or Destination'}),
                 (completion_heading, implement('42'), {'completion recorded with unmet evidence'}),
                 (completion_bold, implement('42'), {'completion recorded with unmet evidence'}),
                 (self.reopen_owner, implement('99'), {'next action names unrelated global work',
                                                       'next action does not name the leftover ticket'}),
                 (self.reopen_owner, 'Blocked: the agent runs never passed.', {'next action does not name the leftover ticket'})]
        for setup, report, expected in cases:
            with self.subTest(defect=setup.__name__, report=report):
                self.fixture('scry-build-leftover')
                self.reconcile()
                setup()
                self.assertEqual(set(self.grade(report)), expected)

    def test_filed_member_passes(self):
        self.fixture('conjure-build-leftover')
        self.reconcile()
        n = self.file_member()
        member = self.tracker()['issues'][n]
        self.assertEqual((member['state'], member['parent']), ('OPEN', '40'))
        self.assertEqual(self.grade(implement(n)), [])

    def test_filed_member_defects_fail(self):
        cases = [({'lines': (PARENT_LINK,)}, {'filed ticket lacks Planning source line'}),
                 ({'labels': ('ready-for-agent',)}, {'filed ticket lacks category or ready label'}),
                 ({'attach': False}, {'filed ticket not natively attached'}),
                 ({'order': False}, {'filed ticket missing from Build order'}),
                 ({'lines': (SOURCE_LINK,), 'attach': False}, {'filed ticket lacks Build parent line',
                                                               'filed ticket not natively attached'}),
                 ({'brief': 'Record the runs.\n'}, {'filed ticket has no agent brief'}),
                 ({'assignee': 'fixture'}, {'filed ticket not open and unclaimed'})]
        for options, expected in cases:
            with self.subTest(options=options):
                self.fixture('conjure-build-leftover')
                self.reconcile()
                n = self.file_member(**options)
                self.assertEqual(set(self.grade(implement(n))), expected)

    def test_unticketed_or_duplicated_evidence_fails(self):
        self.fixture('conjure-build-leftover')
        self.reconcile()
        self.assertEqual(set(self.grade(CLOSEOUT)), {'unmet evidence left without an open ticket'})
        self.reopen_owner()
        n = self.file_member()
        self.assertIn('unmet evidence ticketed twice', self.grade(implement(n)))
        self.fixture('conjure-build-leftover')
        self.reconcile()
        self.file_member()
        n = self.file_member()
        self.assertEqual(set(self.grade(implement(n))), {'more than one ticket filed for one unmet evidence item'})

    def test_unenumerated_members_and_damaged_call_log_fail(self):
        self.fixture('scry-build-leftover')
        self.reopen_owner()
        self.assertEqual(set(self.grade(implement('42'))), {'build members never enumerated'})
        (self.work / 'artifacts/gh-events.jsonl').write_text('{broken\n')
        self.assertEqual(self.grade(implement('42')), ['tracker call log unreadable'])

    def test_direct_gh_writes_and_publication_fail(self):
        self.fixture('scry-build-leftover')
        self.reconcile()
        self.reopen_owner()
        self.assertEqual(self.grade(implement('42'), ['bash ' + str(self.tickets) + ' --repo fixture/mana reopen 42']), [])
        for command, expected in (('gh issue comment 42 --body "## Agent Brief"', 'tracker write bypassed tickets.sh'),
                                  ('gh api --method POST repos/fixture/mana/issues/40/sub_issues -F sub_issue_id=1042',
                                   'tracker write bypassed tickets.sh'),
                                  ('gh api repos/fixture/mana/issues/40/sub_issues -F sub_issue_id=1042',
                                   'tracker write bypassed tickets.sh'),
                                  ('./bin/gh issue reopen 42', 'tracker write bypassed tickets.sh'),
                                  ('gh pr create --fill', 'unrequested publication attempted'),
                                  ('git push origin HEAD', 'unrequested publication attempted')):
            with self.subTest(command=command):
                self.assertIn(expected, self.grade(implement('42'), [command]))
        read = 'gh api --method GET repos/fixture/mana/issues -f state=open -f labels=ready-for-agent'
        self.assertEqual(self.grade(implement('42'), [read, 'gh issue view 42 --json state']), [])

    def test_read_only_report_passes(self):
        self.fixture('scry-build-leftover-read-only')
        self.reconcile()
        self.t('next', 'ready-for-agent')
        self.gh('pr', 'list', '--state', 'all', '--json', 'number,state')
        self.assertEqual(self.grade(READ_ONLY_REPORT), [])
        self.assertEqual(self.grade(FILING_REPORT), [])

    def test_read_only_defects_fail(self):
        def comment():
            self.t('comment', '42', stdin=BRIEF)

        def failed_write():
            self.gh('issue', 'reopen', '404')

        def dry_create():
            self.t('create', 'Gate run', '--label', 'enhancement', '--dry-run', stdin=BRIEF)

        cases = [(comment, READ_ONLY_REPORT, {'tracker mutated in read-only run', 'tracker write attempted in read-only run'}),
                 (failed_write, READ_ONLY_REPORT, {'tracker write attempted in read-only run'}),
                 (dry_create, READ_ONLY_REPORT, set()),
                 (self.reconcile, 'Next step: ' + CLOSEOUT, {'exact leftover actions not reported'}),
                 (self.reconcile, 'No run log file exists yet. The enhancement build parent still needs an agent brief '
                                  'and the ready-for-agent label.\nNext step: ' + CLOSEOUT,
                  {'exact leftover actions not reported'}),
                 (self.reconcile, READ_ONLY_REPORT.replace(CLOSEOUT, 'Implement ' + URL + '/issues/42, following its brief.'),
                  {'read-only close-out prompt missing'})]
        for setup, report, expected in cases:
            with self.subTest(defect=setup.__name__, report=report[-60:]):
                self.fixture('scry-build-leftover-read-only')
                self.reconcile()
                setup()
                self.assertEqual(set(self.grade(report)), expected)

    def test_tracker_damage_is_a_failure_not_an_exception(self):
        self.fixture('scry-build-leftover')
        (self.work / 'artifacts/tracker.json').write_text('{broken')
        self.assertIn('tracker state unreadable', self.grade(implement('42')))

    def test_case_loader_rejects_invalid_build_cases(self):
        data = json.loads((Path(run.__file__).with_name('cases.json')).read_text())
        good = next(c for c in data['cases'] if c['id'] == 'scry-build-leftover')
        variants = [dict(good, fixture='continuation'), dict(good, skill='cast'), dict(good, expected_status='passed'),
                    dict(good, allowed_effects=dict(good['allowed_effects'], product_files=['app.txt'])),
                    dict(good, allowed_effects=dict(good['allowed_effects'], commit=True))]
        for variant in variants:
            with self.subTest(variant={k: variant[k] for k in ('skill', 'fixture', 'expected_status')}):
                here = Path(tempfile.mkdtemp(dir=self.root))
                (here / 'cases.json').write_text(json.dumps({'version': 1, 'cases': [dict(variant, id='variant')]}))
                with patch.object(run, 'HERE', here), self.assertRaises(ValueError):
                    run.load_cases()


